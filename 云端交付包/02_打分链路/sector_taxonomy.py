INDUSTRY_TO_DIR = {ind: d for d, lst in DIRECTIONS.items() for ind in lst}


def direction_of(industry):
    """细分行业 → L1 方向；未收录时返回 None（调用方须显式处理，不得静默丢弃）"""
    if not industry:
        return None
    return INDUSTRY_TO_DIR.get(str(industry).strip())


def direction_order():
    return list(DIRECTIONS.keys())


def coverage_report(all_industries):
    """自检：返回 (已归类数, 未归类清单) —— 未归类必须人工确认后再补进 DIRECTIONS"""
    known = [i for i in all_industries if direction_of(i)]
    unknown = sorted([i for i in all_industries if not direction_of(i)])
    return len(known), unknown
